#!/usr/bin/env bash
# Tests for cut-rc.sh in throwaway repositories: a bare origin and a clone, a
# fake `gh` answering the pull-request query, and local git identities. Covers
# every refusal and one happy path (the version bump, the signed-off commit,
# the tag and the pushes): `bash scripts/cut-rc.test.sh`.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
SCRIPT=$HERE/cut-rc.sh
TMP=$(mktemp -d "${TMPDIR:-/tmp}/cut-rc-test.XXXXXX")
trap 'rm -rf "$TMP"' EXIT
PASSED=0
FAILED=0
ok() { PASSED=$((PASSED + 1)); }
fail() { FAILED=$((FAILED + 1)); echo "FAIL: $*" >&2; }
N=0

# The fake gh: `api --paginate <url> --jq <filter>` runs jq with the filter
# against $FAKE_JSON, with $FAKE_REPO and $FAKE_SHA in the environment the
# filter reads (env.REPO, env.SHA); every call is logged to $FAKE_LOG.
cat > "$TMP/gh" <<'SH'
#!/usr/bin/env bash
echo "$*" >> "$FAKE_LOG"
if [ "$1" = api ] && [ "$2" = --paginate ]; then
  REPO=$FAKE_REPO SHA=$FAKE_SHA jq -r "$5" "$FAKE_JSON"
  exit 0
fi
echo "unexpected call: $*" >&2
exit 2
SH
chmod +x "$TMP/gh"

# A fresh bare origin and a clone of it, on main, then a `feat` branch pushed
# with HEAD as its head. $ORIGIN, $CLONE and $SHA are set.
begin() {
  N=$((N + 1))
  ORIGIN=$TMP/origin-$N.git
  CLONE=$TMP/clone-$N
  git init -q --bare "$ORIGIN"
  git clone -q "$ORIGIN" "$CLONE"
  cd "$CLONE"
  git config user.name Test
  git config user.email test@example.com
  git checkout -q -b main
  mkdir -p crates/droppen-server docs/releases
  printf '[package]\nname = "droppen-server"\nversion = "0.2.0"\nedition = "2021"\n' > crates/droppen-server/Cargo.toml
  printf '# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = "droppen-server"\nversion = "0.2.0"\n\n[[package]]\nname = "other"\nversion = "9.9.9"\n' > Cargo.lock
  printf '# Droppen v0.1.0\n\nAn earlier release.\n' > docs/releases/v0.1.0.md
  git add .
  git commit -q -m init
  git push -q origin main
  git checkout -q -b feat
  git push -q -u origin feat
  SHA=$(git rev-parse HEAD)
}

# pr json: number, state, headRefOid, base ref, head repository
pr_json() {
  printf '{"number":%s,"state":"%s","headRefOid":"%s","base":{"ref":"%s"},"head":{"repo":{"full_name":"%s"}},"html_url":"https://github.com/getdroppen/droppen/pull/%s"}' \
    "$1" "$2" "$3" "$4" "$5" "$1"
}
# The one qualifying pull request for the current commit.
good_pr() { pr_json 7 open "$SHA" main getdroppen/droppen; }

# The bilingual banner and nothing about an app.
write_notes() { # version (with v)
  {
    echo "# Droppen $1"
    echo
    echo "This is a **test release** of the branch."
    echo
    echo "这是一个**测试版本**。"
  } > "docs/releases/$1.md"
}

run() { # expected exit, description, fixture json, version, [tag state: gone|present], [tree state: clean|changed]
  local want=$1 what=$2 json=$3 ver=$4 tag_state=${5:-gone} tree_state=${6:-clean} expect_commit=${7:-no} got=0
  case "$json" in
    \[*) printf '%s' "$json" > "$TMP/pulls.json" ;;
    *) printf '[%s]' "$json" > "$TMP/pulls.json" ;;
  esac
  LOG=$TMP/log-$PASSED-$FAILED
  OUT=$TMP/out-$PASSED-$FAILED
  : > "$LOG"
  env PATH="$TMP:$PATH" GITHUB_REPOSITORY=getdroppen/droppen FAKE_LOG="$LOG" \
    FAKE_JSON="$TMP/pulls.json" FAKE_REPO=getdroppen/droppen FAKE_SHA="$SHA" \
    bash "$SCRIPT" "$ver" > "$OUT" 2>&1 || got=$?
  [ "$got" = "$want" ] && ok || { fail "$what: exit $got, want $want"; cat "$OUT" >&2; }
  if [ "$want" = 1 ]; then
    if [ "$expect_commit" = yes ]; then
      [ "$(git rev-parse HEAD)" != "$SHA" ] && ok || fail "$what: did not make a commit"
    else
      [ "$(git rev-parse HEAD)" = "$SHA" ] && ok || fail "$what: made a commit"
    fi
    if [ "$tag_state" = gone ]; then
      [ -z "$(git rev-parse -q --verify refs/tags/v0.2.0-rc.1 2>/dev/null)" ] && ok || fail "$what: made the tag"
    fi
    if [ "$tree_state" = clean ]; then
      [ -z "$(git status --porcelain | grep -v 'docs/releases/v0.2.0-rc.1.md' || true)" ] && ok || fail "$what: changed the tree"
    else
      [ -n "$(git status --porcelain | grep -v 'docs/releases/v0.2.0-rc.1.md' || true)" ] && ok || fail "$what: did not notice the tree change"
    fi
  fi
}

# --- refusals ---------------------------------------------------------------

begin
git checkout -q main
run 1 "on main" "$(good_pr)" v0.2.0-rc.1
grep -qF 'on main' "$OUT" && ok || fail "says it is on main"

begin
run 1 "no pull request" '[]' v0.2.0-rc.1
grep -qF 'no open pull request to main' "$OUT" && ok || fail "says there is no pull request"

begin
run 1 "a pull request whose head moved" "$(pr_json 7 open 1111111111111111111111111111111111111111 main getdroppen/droppen)" v0.2.0-rc.1
grep -qF 'no open pull request to main' "$OUT" && ok || fail "says the commit is not the head"

begin
run 1 "a closed pull request" "$(pr_json 7 closed "$SHA" main getdroppen/droppen)" v0.2.0-rc.1
grep -qF 'no open pull request to main' "$OUT" && ok || { fail "refuses a closed pull request"; cat "$OUT" >&2; }

begin
run 1 "a fork's pull request" "$(pr_json 7 open "$SHA" main someone/droppen)" v0.2.0-rc.1
grep -qF 'fork' "$OUT" && ok || fail "names the fork"

begin
run 1 "a pull request to another branch" "$(pr_json 7 open "$SHA" release getdroppen/droppen)" v0.2.0-rc.1
grep -qF 'no open pull request to main' "$OUT" && ok || fail "refuses another base"

begin
write_notes v0.2.0-rc.1
git tag v0.2.0-rc.2
run 1 "a version older than the newest rc" "$(good_pr)" v0.2.0-rc.1
grep -qF 'older than v0.2.0-rc.2' "$OUT" && ok || fail "says the version is older"

# A hand tag beside the rc.N series (v0.2.0-rc.1-old) sorts after rc.1 under
# sort -V: it must not make the real rc.1 look older.
begin
write_notes v0.2.0-rc.1
git tag v0.2.0-rc.1-old
run 0 "a hand tag beside the rc series" "$(good_pr)" v0.2.0-rc.1
grep -qF 'older than' "$OUT" && fail "counted the hand tag as newer" || ok

begin
write_notes v0.2.0-rc.1
git tag v0.2.0-rc.1
run 1 "a tag that exists locally" "$(good_pr)" v0.2.0-rc.1 present
grep -qF 'exists locally' "$OUT" && ok || fail "says the tag exists locally"

begin
write_notes v0.2.0-rc.1
git tag v0.2.0-rc.1
git push -q origin v0.2.0-rc.1
git tag -d v0.2.0-rc.1 >/dev/null
run 1 "a tag that exists on origin" "$(good_pr)" v0.2.0-rc.1
grep -qF 'exists on origin' "$OUT" && ok || fail "says the tag exists on origin"

begin
run 1 "missing notes" "$(good_pr)" v0.2.0-rc.1
grep -qF 'missing or empty' "$OUT" && ok || fail "says the notes are missing"

begin
: > docs/releases/v0.2.0-rc.1.md
run 1 "empty notes" "$(good_pr)" v0.2.0-rc.1
grep -qF 'missing or empty' "$OUT" && ok || fail "says the notes are empty"

begin
printf '# Droppen v0.2.0-rc.1\n\nNo banner here.\n' > docs/releases/v0.2.0-rc.1.md
run 1 "notes without the banner" "$(good_pr)" v0.2.0-rc.1
grep -qF 'test release' "$OUT" && ok || fail "asks for the English banner"

begin
write_notes v0.2.0-rc.1
echo 'The app: Droppen-0.2.0-rc.1.dmg' >> docs/releases/v0.2.0-rc.1.md
run 1 "notes naming the RC's app" "$(good_pr)" v0.2.0-rc.1
grep -qF 'server-only' "$OUT" && ok || fail "says a prerelease is server-only"

begin
write_notes v0.2.0-rc.1
echo 'Sources: Droppen-0.2.0-rc.1-linux-sources.tar' >> docs/releases/v0.2.0-rc.1.md
run 1 "notes naming the Linux sources tar" "$(good_pr)" v0.2.0-rc.1
grep -qF 'server-only' "$OUT" && ok || fail "refuses the sources tar too"

begin
write_notes v0.2.0-rc.1
echo 'The app comes with Droppen-0.2.0.dmg.' >> docs/releases/v0.2.0-rc.1.md
run 0 "notes naming the final release's app" "$(good_pr)" v0.2.0-rc.1
[ "$(git log -1 --format=%s)" = "chore: release v0.2.0-rc.1" ] && ok || fail "made the commit for a final-version DMG note"

# The branch may already carry the version and the notes (the bump committed,
# the tag push still to do): then only the tag is made.
begin
write_notes v0.2.0-rc.1
printf '[package]\nname = "droppen-server"\nversion = "0.2.0-rc.1"\nedition = "2021"\n' > crates/droppen-server/Cargo.toml
printf '# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = "droppen-server"\nversion = "0.2.0-rc.1"\n\n[[package]]\nname = "other"\nversion = "9.9.9"\n' > Cargo.lock
git add -A && git commit -q -m "prepare the rc" && git push -q
SHA=$(git rev-parse HEAD)
before=$(git rev-list --count HEAD)
run 0 "a branch that already carries the version" "$(good_pr)" v0.2.0-rc.1
[ "$(git rev-list --count HEAD)" = "$before" ] && ok || fail "committed an empty bump"
[ "$(git rev-parse v0.2.0-rc.1^{commit})" = "$SHA" ] && ok || fail "tagged the already-carried commit"
[ -n "$(git ls-remote origin refs/tags/v0.2.0-rc.1)" ] && ok || fail "pushed the tag"

# A failed branch push must not push the tag on a commit the branch lacks.
begin
write_notes v0.2.0-rc.1
printf '#!/bin/sh\nexit 1\n' > "$ORIGIN/hooks/pre-receive"
chmod +x "$ORIGIN/hooks/pre-receive"
run 1 "a branch push that fails" "$(good_pr)" v0.2.0-rc.1 present clean yes
grep -qE 'Retry|Push the branch' "$OUT" && ok || fail "says how to retry"
[ -n "$(git rev-parse -q --verify refs/tags/v0.2.0-rc.1 2>/dev/null)" ] && ok || fail "kept the local tag"
[ -z "$(git ls-remote origin refs/tags/v0.2.0-rc.1)" ] && ok || fail "pushed the tag without the branch"

begin
write_notes v0.2.0-rc.1
echo stray > stray.txt
run 1 "an unrelated change" "$(good_pr)" v0.2.0-rc.1 gone changed
grep -qF 'other changes' "$OUT" && ok || fail "says the tree has other changes"
rm stray.txt

# --- the happy path ---------------------------------------------------------

begin
write_notes v0.2.0-rc.1
run 0 "the happy path" "$(good_pr)" v0.2.0-rc.1
grep -qx 'version = "0.2.0-rc.1"' crates/droppen-server/Cargo.toml && ok || fail "bumped Cargo.toml"
lock_version() { awk -v p="$1" '$0 == "name = \"" p "\"" { found = 1; next } found && /^version = / { sub(/^version = "/, ""); sub(/"$/, ""); print; exit }' Cargo.lock; }
[ "$(lock_version droppen-server)" = "0.2.0-rc.1" ] && ok || fail "bumped the droppen-server lock entry"
[ "$(lock_version other)" = "9.9.9" ] && ok || fail "left another package's lock entry alone"
[ "$(git log -1 --format=%s)" = "chore: release v0.2.0-rc.1" ] && ok || fail "commit subject"
git log -1 --format=%B | grep -qx 'Signed-off-by: Test <test@example.com>' && ok || fail "signed off"
git tag -l --format='%(contents)' v0.2.0-rc.1 | grep -qx 'Droppen v0.2.0-rc.1' && ok || fail "tag message"
[ "$(git rev-parse v0.2.0-rc.1^{commit})" = "$(git rev-parse HEAD)" ] && ok || fail "tag points at the commit"
[ "$(git ls-remote origin refs/heads/feat | cut -f 1)" = "$(git rev-parse HEAD)" ] && ok || fail "pushed the branch"
[ -n "$(git ls-remote origin refs/tags/v0.2.0-rc.1)" ] && ok || fail "pushed the tag"
grep -qF 'pull request: https://github.com/getdroppen/droppen/pull/7' "$OUT" && ok || fail "prints the pull request"
grep -qF 'actions/workflows/release.yml' "$OUT" && ok || fail "prints the Actions URL"

echo "cut-rc: $PASSED passed, $FAILED failed"
[ "$FAILED" = 0 ]
