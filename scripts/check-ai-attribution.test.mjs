// Tests for scripts/check-ai-attribution.mjs: `node --test scripts/check-ai-attribution.test.mjs`.
//
// The matchers on their own, then the whole check, as CI runs it, over a small
// git repository made here: a base commit, and on top of it commits with and
// without the lines and addresses it looks for. Needs git, nothing else.

import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, describe, test } from "node:test";
import { fileURLToPath } from "node:url";
import { attributionLines, commitsIn, findAttribution } from "./check-ai-attribution.mjs";

const SCRIPT = fileURLToPath(new URL("./check-ai-attribution.mjs", import.meta.url));

// Built from parts, so this file's own lines are not what it looks for.
const CO = "Co-Authored-By";
const GEN = "Generated with";
const VENDOR = ["noreply", "anthropic.com"].join("@");

describe("lines", () => {
  test("co-author trailers naming an AI tool or its vendor, in any case", () => {
    for (const line of [
      `${CO}: Claude <${VENDOR}>`,
      `${CO.toLowerCase()}: Claude Code <${VENDOR}>`,
      `${CO.toUpperCase()}: someone <${VENDOR}>`,
      `  ${CO}: GitHub Copilot <copilot@github.com>`,
      `${CO}: ChatGPT <chatgpt@openai.com>`,
      `${CO}: Codex <codex@openai.com>`,
      `${CO}: Gemini <gemini@google.com>`,
      `${CO}: Cursor Agent <cursoragent@cursor.com>`,
      `${CO}: Some Bot <bot@anthropic.example>`,
    ]) {
      assert.deepEqual(attributionLines(`fix: a thing\n\nbody\n\n${line}\n`), [line.trim()], line);
    }
  });

  test("generated-with lines, as the tools write them", () => {
    for (const line of [
      `🤖 ${GEN} [Claude Code](https://claude.com/claude-code)`,
      `${GEN} Claude Code`,
      `_${GEN.toLowerCase()} ChatGPT_`,
      "Generated by Copilot",
      "Generated by codex",
      "> Generated by an AI assistant",
    ]) {
      assert.deepEqual(attributionLines(`docs: x\n\n${line}`), [line.trim()], line);
    }
  });

  test("people, sign-offs and prose about the tools are not", () => {
    const message = [
      "feat(sessions): resume sessions generated by Claude Code and Codex",
      "",
      "A transcript generated with Claude keeps its tool calls; the Copilot",
      "and Gemini adapters are next.",
      "",
      `${CO}: Ada Lovelace <ada@example.com>`,
      "Signed-off-by: Ada Lovelace <ada@example.com>",
      "Reviewed-by: Claude Shannon? no: a reviewer line, not a co-author",
    ].join("\n");
    assert.deepEqual(attributionLines(message), []);
    assert.deepEqual(attributionLines(""), []);
    assert.deepEqual(attributionLines(undefined), []);
  });
});

describe("findings", () => {
  test("each commit's lines and vendor addresses, then the title and body", () => {
    const found = findAttribution({
      commits: [
        { sha: "a1", authorEmail: "ada@example.com", committerEmail: "noreply@github.com", message: "fix: fine\n" },
        { sha: "b2", authorEmail: VENDOR, committerEmail: VENDOR.toUpperCase(), message: `fix: x\n\n${CO}: Claude <${VENDOR}>\n` },
      ],
      title: "fix: fine",
      body: `Does a thing.\n\n🤖 ${GEN} [Claude Code](https://claude.com/claude-code)\n`,
    });
    assert.deepEqual(found, [
      { where: "commit b2", what: `author email ${VENDOR}` },
      { where: "commit b2", what: `committer email ${VENDOR.toUpperCase()}` },
      { where: "commit b2", what: `${CO}: Claude <${VENDOR}>` },
      { where: "the pull request's body", what: `🤖 ${GEN} [Claude Code](https://claude.com/claude-code)` },
    ]);
  });

  test("nothing to find", () => {
    assert.deepEqual(findAttribution(), []);
    assert.deepEqual(findAttribution({ commits: [{ sha: "c3", authorEmail: "a@b.c", committerEmail: "a@b.c", message: "ci: y" }] }), []);
  });
});

describe("the check over a git repository", () => {
  const dir = mkdtempSync(join(tmpdir(), "check-ai-attribution-"));
  after(() => rmSync(dir, { recursive: true, force: true }));
  const env = {
    ...process.env,
    GIT_CONFIG_GLOBAL: join(dir, "no-global-config"),
    GIT_CONFIG_NOSYSTEM: "1",
    GIT_AUTHOR_NAME: "Ada Lovelace",
    GIT_AUTHOR_EMAIL: "ada@example.com",
    GIT_COMMITTER_NAME: "Ada Lovelace",
    GIT_COMMITTER_EMAIL: "ada@example.com",
  };
  const git = (args, extra = {}) => execFileSync("git", args, { cwd: dir, env: { ...env, ...extra }, encoding: "utf8" }).trim();
  let n = 0;
  const commit = (message, extra = {}) => {
    writeFileSync(join(dir, "file"), `${++n}\n`);
    git(["add", "file"]);
    git(["commit", "-q", "-m", message], extra);
    return git(["rev-parse", "HEAD"]);
  };
  const run = (range, { title = "", body = "" } = {}) => {
    const r = spawnSync(process.execPath, [SCRIPT, range], {
      cwd: dir,
      env: { ...env, PR_TITLE: title, PR_BODY: body },
      encoding: "utf8",
    });
    return { status: r.status, out: r.stdout, err: r.stderr };
  };

  git(["init", "-q", "-b", "main"]);
  // On the base branch already: never this pull request's to answer for.
  commit(`feat: old\n\n${CO}: Claude <${VENDOR}>\nSigned-off-by: Ada Lovelace <ada@example.com>`);
  const base = git(["rev-parse", "HEAD"]);
  git(["checkout", "-q", "-b", "topic"]);
  const clean = commit("fix: one\n\nSigned-off-by: Ada Lovelace <ada@example.com>");
  const human = commit(`fix: two\n\n${CO}: Grace Hopper <grace@example.com>\nSigned-off-by: Ada Lovelace <ada@example.com>`);

  test("clean commits, title and body pass, whatever the base branch has", () => {
    const r = run(`${base}..${human}`, { title: "fix: one and two", body: "Two fixes.\n\nSessions generated by Codex resume too." });
    assert.equal(r.status, 0, r.out + r.err);
    assert.match(r.out, /^ok: no AI attribution in 2 commit\(s\)/m);
    assert.deepEqual(
      commitsIn(`${base}..${human}`, dir).map((c) => c.sha),
      [human, clean],
    );
  });

  test("a trailer, a generated-with line and a vendor address each fail, with the commit and the line", () => {
    const trailer = commit(`fix: three\n\n${CO}: Claude Code <${VENDOR}>\nSigned-off-by: Ada Lovelace <ada@example.com>`);
    const generated = commit(`docs: four\n\n🤖 ${GEN} [Claude Code](https://claude.com/claude-code)`);
    const authored = commit("chore: five", { GIT_AUTHOR_EMAIL: VENDOR });
    const r = run(`${base}..HEAD`, { title: "fix: three to five" });
    assert.equal(r.status, 1, r.out + r.err);
    const errors = r.out.split("\n").filter((l) => l.startsWith("::error::"));
    assert.deepEqual(errors, [
      `::error::commit ${authored}: author email ${VENDOR}`,
      `::error::commit ${generated}: 🤖 ${GEN} [Claude Code](https://claude.com/claude-code)`,
      `::error::commit ${trailer}: ${CO}: Claude Code <${VENDOR}>`,
    ]);
    assert.match(r.err, /3 AI attribution line\(s\) or address\(es\)/);
  });

  test("the title and the body are checked too", () => {
    const r = run(`${base}..${human}`, { title: "fix: two", body: `Two.\n\n${GEN} Claude Code\n` });
    assert.equal(r.status, 1, r.out + r.err);
    assert.match(r.out, new RegExp(`^::error::the pull request's body: ${GEN} Claude Code$`, "m"));
  });

  test("a committer address counts as much as an author's", () => {
    const committed = commit("chore: six", { GIT_COMMITTER_EMAIL: VENDOR });
    const r = run(`HEAD~1..HEAD`);
    assert.equal(r.status, 1, r.out + r.err);
    assert.match(r.out, new RegExp(`^::error::commit ${committed}: committer email ${VENDOR}$`, "m"));
  });

  test("a range git cannot list, or an empty one, is an error, not a pass", () => {
    assert.equal(run("no-such-branch..HEAD").status, 2);
    assert.equal(run("HEAD..HEAD").status, 2);
    assert.equal(spawnSync(process.execPath, [SCRIPT], { cwd: dir, env, encoding: "utf8" }).status, 2);
  });
});
