/// The label TypeScript gives a chain error (`ChainErrorKind`).
pub(crate) fn chain_error_kind(e: &ChainError) -> &'static str {
    match e {
        ChainError::Decode(_) => "decode",
        ChainError::Version(_) => "version",
        ChainError::BadSignature { .. } => "badSignature",
        ChainError::WrongAccount { .. } => "wrongAccount",
        ChainError::OutOfOrder { .. } => "outOfOrder",
        ChainError::BrokenLink { .. } => "brokenLink",
        ChainError::NotGenesis => "notGenesis",
        ChainError::LateGenesis { .. } => "lateGenesis",
        ChainError::PinMismatch => "pinMismatch",
        ChainError::GenesisMismatch => "genesisMismatch",
        ChainError::NotAllowed { .. } => "notAllowed",
        ChainError::DuplicateId { .. } => "duplicateId",
        ChainError::UnknownId { .. } => "unknownId",
        ChainError::LastFullDevice { .. } => "lastFullDevice",
        ChainError::LastAdmin { .. } => "lastAdmin",
        ChainError::UnknownSlot { .. } => "unknownSlot",
        ChainError::WeakKey { .. } => "weakKey",
        ChainError::BadId { .. } => "badId",
        ChainError::TooEarly { .. } => "tooEarly",
        ChainError::Rollback { .. } => "rollback",
        ChainError::Fork { .. } => "fork",
        ChainError::Behind { .. } => "behind",
        ChainError::UnknownDevice(_) => "unknownDevice",
        ChainError::BadAttestation(_) => "badAttestation",
        ChainError::UncommittedKey { .. } => "uncommittedKey",
        ChainError::KeyMismatch { .. } => "keyMismatch",
        ChainError::NotAccepted { .. } => "notAccepted",
        ChainError::SelfControl => "selfControl",
    }
}

/// Verify `entries` (hex, possibly not decodable) as a chain: the error's label.
pub(crate) fn verify_label(entries: &[Value]) -> Result<ChainState, &'static str> {
    let decoded = entries
        .iter()
        .map(|e| Entry::decode(&hexv(e)))
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| chain_error_kind(&e))?;
    ChainState::verify(&decoded, None, &mut ChainClock::history()).map_err(|e| chain_error_kind(&e))
}

/// A v3 state as both halves' vectors write it: every device with its flags
/// and history, the current hosts and admins, the passkey slots, and — for
/// `hosts` — the accept policy and the committed machine key epochs.
pub(crate) fn v3_state_json(state: &ChainState, hosts: &[&str]) -> Value {
    use crate::chain::Accept;
    let status = |d: &crate::chain::DeviceRecord| match d.status {
        DeviceStatus::Active => "active",
        DeviceStatus::Pending { .. } => "pending",
        DeviceStatus::Removed => "removed",
    };
    let accept_json = |a: &Accept| match a {
        Accept::Admins => json!({"kind": "admins"}),
        Accept::All => json!({"kind": "all"}),
        Accept::Devices(ids) => json!({"kind": "devices", "ids": ids}),
    };
    json!({
        "seq": state.seq(),
        "head": h(&state.head()),
        "v3From": state.v3_from(),
        "recoveryKey": state.recovery_key().map(|k| h(&k)),
        "devices": state.devices().map(|d| json!({
            "id": d.info.id, "host": d.host, "admin": d.admin, "status": status(d),
            "viaRecovery": d.via_recovery, "viaPasskey": d.via_passkey, "addedSeq": d.added_seq, "activatedSeq": d.activated_seq,
        })).collect::<Vec<_>>(),
        "machines": state.devices().filter(|d| state.machine(&d.info.id).is_some()).map(|d| d.info.id.clone()).collect::<Vec<_>>(),
        "admins": state.admins().map(|d| d.info.id.clone()).collect::<Vec<_>>(),
        "slots": state.slots().map(|s| json!({"slot": s.slot.slot, "setBy": s.set_by, "removed": s.removed, "addedSeq": s.added_seq})).collect::<Vec<_>>(),
        "accept": hosts.iter().map(|host| json!({"host": host, "from": accept_json(&state.accept_policy(host))})).collect::<Vec<_>>(),
        "userKeyEpochs": state.user_key_epochs(),
        "machineKeyEpochs": hosts.iter().map(|host| (host.to_string(), json!(state.machine_key_epochs(host)))).collect::<serde_json::Map<_, _>>(),
    })
}

/// The reason a chain of `entries` (hex) is refused with, when it is
/// `NotAllowed`: the rule, which both halves must name alike.
pub(crate) fn not_allowed_reason(entries: &[Value]) -> Option<&'static str> {
    let decoded = entries.iter().map(|e| Entry::decode(&hexv(e))).collect::<Result<Vec<_>, _>>().ok()?;
    match ChainState::verify(&decoded, None, &mut ChainClock::history()) {
        Err(ChainError::NotAllowed { reason, .. }) => Some(reason),
        _ => None,
    }
}

