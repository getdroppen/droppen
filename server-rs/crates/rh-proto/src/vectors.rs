/// Encodings `ed25519_key` refuses as weak, which the TypeScript half refuses too.
fn weak_ed25519_encodings() -> Vec<[u8; 32]> {
    use curve25519_dalek::constants::EIGHT_TORSION;
    let mut candidates: Vec<[u8; 32]> = Vec::new();
    for point in EIGHT_TORSION.iter() {
        let c = point.compress().to_bytes();
        candidates.push(c);
        let mut flipped = c;
        flipped[31] ^= 0x80;
        candidates.push(flipped);
    }
    // y = p and y = p + 1: non-canonical spellings of y = 0 and y = 1.
    for low in [0xed, 0xee] {
        for sign in [0x7f, 0xff] {
            let mut e = [0xff; 32];
            e[0] = low;
            e[31] = sign;
            candidates.push(e);
        }
    }
    let mut weak: Vec<[u8; 32]> = candidates.into_iter().filter(|c| ed25519_key(c).is_none()).collect();
    weak.sort();
    weak.dedup();
    weak
}

fn key_vectors() -> Value {
    let mut one = [0u8; 32];
    one[0] = 1;
    let low_order: Vec<Vec<u8>> = vec![
        vec![0; 32],
        one.to_vec(),
        // The u-coordinates of the order-8 points.
        hex::decode("e0eb7a7c3b41b8ae1656e3faf19fc46ada098deb9c32b1fd866205165f49b800"),
        hex::decode("5f9c95bca3508c24b1d0b1559c83ef5b04445cc4581c8e86d8224eddd09f1157"),
    ];
    for key in &low_order {
        assert!(x25519_is_low_order(&key.clone().try_into().unwrap()));
    }
    // A good signature, and the same one with S + L (a second, non-canonical spelling).
    let key = SigningKey::from_bytes(&bytes32(40));
    let message = b"rh/v1 strictness".to_vec();
    let sig = ed25519_dalek::Signer::sign(&key, &message).to_bytes();
    let mut high = sig;
    let l = hex::decode("edd3f55c1a631258d69cf7a2def9de1400000000000000000000000000000010");
    let mut carry = 0u16;
    for i in 0..32 {
        let sum = u16::from(high[32 + i]) + u16::from(l[i]) + carry;
        high[32 + i] = sum as u8;
        carry = sum >> 8;
    }
    assert!(!crate::keys::ed25519_verify(&key.verifying_key().to_bytes(), &message, &high));
    // Encodings at the edges, and whether each side must accept them.
    let le = |n: u64, top: u8| {
        let mut b = [0u8; 32];
        b[..8].copy_from_slice(&n.to_le_bytes());
        b[31] |= top;
        b
    };
    let p_plus = |k: u8| {
        let mut b = [0xffu8; 32];
        b[0] = 0xed + k;
        b[31] = 0x7f;
        b
    };
    let good_dh = DhKeypair::from_secret(bytes32(41)).public();
    let mut good_dh_high = good_dh;
    good_dh_high[31] |= 0x80;
    let mut p_minus_1 = p_plus(0);
    p_minus_1[0] = 0xec;
    let x_candidates: Vec<[u8; 32]> = vec![
        le(0, 0),
        le(1, 0),
        le(1, 0x80),
        p_minus_1,
        p_plus(0),
        p_plus(1),
        good_dh,
        good_dh_high,
        low_order[2].clone().try_into().unwrap(),
        low_order[3].clone().try_into().unwrap(),
    ];
    let good_ed = SigningKey::from_bytes(&bytes32(42)).verifying_key().to_bytes();
    let e_candidates: Vec<[u8; 32]> = vec![good_ed, p_plus(2), p_plus(3), p_plus(4), p_plus(5), le(2, 0)];
    json!({
        "x25519Candidates": x_candidates.iter().map(|k| json!({"key": h(k), "valid": crate::keys::x25519_valid(k)})).collect::<Vec<_>>(),
        "ed25519Candidates": e_candidates.iter().map(|k| json!({"key": h(k), "valid": ed25519_key(k).is_some()})).collect::<Vec<_>>(),
        "ed25519Weak": weak_ed25519_encodings().iter().map(|k| h(k)).collect::<Vec<_>>(),
        "x25519LowOrder": hexes(low_order.iter().map(Vec::as_slice)),
        "signature": {"key": h(&key.verifying_key().to_bytes()), "message": h(&message), "good": h(&sig), "nonCanonical": h(&high)},
    })
}

